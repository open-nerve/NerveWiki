package domain

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
	"testing"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"
)

// TestGrepTablesAreTheirDefinition computes the risky tails (M9/P4 design
// 3.5.3) by their definition, over every code point and every code point
// without an NFC boundary before it, and compares grep_tables.go's with
// them; with NERVE_WRITE_GREP_TABLES set (go generate), it writes the file
// instead. On the way it checks the claims of Unicode the keys rest on
// (3.5.3, 3.5.4): what a new Unicode in Go or x/text changes shows here.
// About a second: it runs under -short too (M9/P4 review C-N5).
func TestGrepTablesAreTheirDefinition(t *testing.T) {
	// The code points without a boundary before them: changing, those whose
	// fold is another text; marks, those NFC keeps, and folded, those of
	// them whose fold is another text. A pair holding one NFC changes is
	// never kept apart.
	var changing, marks, folded []rune
	for m := range unicode.MaxRune + 1 {
		if isSurrogate(m) || boundaryBefore(m) {
			continue
		}
		changes := searchFold(string(m)) != string(m)
		if changes {
			changing = append(changing, m)
		}
		if norm.NFC.String(string(m)) == string(m) {
			marks = append(marks, m)
			if changes {
				folded = append(folded, m)
			}
		}
	}
	var tails, orbits, leading, others []rune
	for r := range unicode.MaxRune + 1 {
		if isSurrogate(r) {
			continue
		}
		s := string(r)
		fr := searchFold(s)
		// Where neither r nor m folds to another text, the folded pair is
		// the pair, which NFC keeps apart: only the marks whose fold is
		// another text can make r risky then.
		candidates := marks
		if fr == s {
			candidates = folded
		}
		for _, m := range candidates {
			pair := s + string(m)
			if norm.NFC.String(pair) == pair && !strings.HasPrefix(norm.NFC.String(fr+searchFold(string(m))), fr) {
				tails = append(tails, r)
				break
			}
		}
		// Every code point of an orbit folds alike: an atom under (?i) folds
		// as its stored code point (step 3).
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			if searchFold(string(f)) != fr {
				orbits = append(orbits, r)
				break
			}
		}
		// None with a boundary before it folds to a text that starts with
		// one without: a piece's first atom stays a sequence's start
		// (3.5.4, 2).
		if first, _ := utf8.DecodeRuneInString(fr); boundaryBefore(r) && fr != "" && !boundaryBefore(first) {
			leading = append(leading, r)
		}
		// The others have a boundary before them, and those a line in NFC
		// holds fold to others alone (othersAlone).
		if classOf(r) == classOther && (!boundaryBefore(r) || norm.NFC.String(s) == s && slices.ContainsFunc([]rune(fr),
			func(x rune) bool { return classOf(x) != classOther })) {
			others = append(others, r)
		}
	}
	t.Logf("%d risky tails; %d code points without a boundary before them in NFC; %d without one fold to another text: %U",
		len(tails), len(marks), len(changing), changing)
	for _, bad := range []struct {
		what  string
		runes []rune
	}{
		{"fold apart from their orbit", orbits},
		{"have a boundary before them and fold to a text that starts without one", leading},
		{"are others without a boundary before them, or in NFC and folding to another class", others},
	} {
		if len(bad.runes) > 0 {
			t.Errorf("%d code points %s: %U", len(bad.runes), bad.what, bad.runes[:min(len(bad.runes), 20)])
		}
	}
	// In NFC, U+0345 alone of them: the others are taken apart (riskyTailSequence).
	if !slices.Equal(folded, []rune{0x345}) {
		t.Errorf("the code points without a boundary before them, in NFC, whose fold is another text: %U, want U+0345 alone", folded)
	}
	if os.Getenv("NERVE_WRITE_GREP_TABLES") != "" {
		writeGrepTables(t, tails)
		return
	}
	var table []rune
	for r := range unicode.MaxRune + 1 {
		if riskyTail(r) {
			table = append(table, r)
		}
	}
	if !slices.Equal(table, tails) {
		t.Errorf("grep_tables.go's risky tails %U, by the definition %U: go generate ./internal/modules/page/domain/", table, tails)
	}
}

func isSurrogate(r rune) bool { return 0xD800 <= r && r <= 0xDFFF }

// writeGrepTables writes grep_tables.go: riskyTail, a switch over tails.
func writeGrepTables(t *testing.T, tails []rune) {
	t.Helper()
	var b strings.Builder
	b.WriteString(`// Code generated by TestGrepTablesAreTheirDefinition (go generate, grep_keys.go); DO NOT EDIT.

package domain

// riskyTail reports whether r is one of the risky tails (M9/P4 design
// 3.5.3): with some code point m without an NFC boundary before it, NFC
// keeps r m apart, and joins searchFold(r) to searchFold(m).
func riskyTail(r rune) bool {
	switch r {
	case `)
	for i, r := range tails {
		if i > 0 {
			b.WriteString(", ")
			if i%8 == 0 {
				b.WriteString("\n\t\t")
			}
		}
		fmt.Fprintf(&b, "0x%04X", r)
	}
	b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("grep_tables.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote grep_tables.go: %d risky tails", len(tails))
}
